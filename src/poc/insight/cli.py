"""Ask the governed assistant a question.

    python -m src.poc.insight.cli --role finance_analyst "What was net revenue by region last quarter?"
    python -m src.poc.insight.cli --demo          # scripted demo: answered, restricted, refused
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
from src.poc.insight.assistant import Assistant  # noqa: E402

EVAL = Path(__file__).resolve().parents[3] / "tests" / "insight_eval.yml"
ICON = {"ANSWERED": "✅", "ANSWERED_RESTRICTED": "🔒", "REFUSED_UNSUPPORTED": "⛔", "REFUSED_UNAUTHORIZED": "⛔"}


def show(r, verbose: bool) -> None:
    print(f"\n{'=' * 100}\n[{r.role}] {r.question}\n{ICON.get(r.status, '')} {r.status}   (audit {r.audit_id})\n")
    print(r.answer)
    for n in r.notes:
        print(f"\n  NOTE: {n}")
    if r.sql:
        owners = ", ".join(f"{m}: owner {v['owner']}, {v['sensitivity']}" for m, v in r.metrics.items())
        print(f"\n  Source: metric catalogue ({owners}); {r.data_as_of}")
        if verbose:
            print("\n  SQL (generated by the metric compiler):\n    " + r.sql.replace("\n", "\n    "))
            print(f"  Parameters: {r.params}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("question", nargs="?")
    ap.add_argument("--role", default="finance_analyst")
    ap.add_argument("--demo", action="store_true")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--sql", action="store_true", help="also print the generated SQL")
    a = ap.parse_args()
    bot = Assistant()
    if a.demo:
        cases = [c for c in yaml.safe_load(EVAL.read_text())["cases"] if c.get("demo")]
        for c in cases:
            show(bot.ask(c["question"], c["role"]), verbose=a.sql)
        print(f"\n{'=' * 100}\nAll requests were written to outputs/audit/insight_audit.jsonl")
        return 0
    if not a.question:
        ap.error("give a question or --demo")
    r = bot.ask(a.question, a.role)
    print(json.dumps(r.to_dict(), default=str, indent=2)) if a.json else show(r, verbose=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
